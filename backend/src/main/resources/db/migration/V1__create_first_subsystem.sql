-- Approved subsystem 1 mapping. No data from subsystem 2/3.

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE muzej (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv text NOT NULL,
    godina_osnivanja integer,
    adresa text NOT NULL,
    opis text,
    aktivan boolean NOT NULL
);

CREATE INDEX ix_muzej_naziv ON muzej (naziv);

CREATE TABLE sala (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    muzej_id bigint NOT NULL REFERENCES muzej(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    naziv text NOT NULL,
    povrsina numeric(19,2),
    sprat integer,
    kapacitet integer
);

CREATE INDEX ix_sala_muzej_id ON sala (muzej_id);

CREATE INDEX ix_sala_naziv ON sala (naziv);

CREATE TABLE izlozba (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sala_id bigint NOT NULL REFERENCES sala(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    naziv text NOT NULL,
    opis text,
    datum_pocetka timestamp with time zone NOT NULL,
    datum_zavrsetka timestamp with time zone NOT NULL,
    status varchar(32) NOT NULL,
    online_vidljiva boolean NOT NULL,
    CONSTRAINT ck_izlozba_period CHECK (datum_zavrsetka > datum_pocetka),
    CONSTRAINT ck_izlozba_status CHECK (status IN ('PLANIRANA','AKTIVNA','ZAVRSENA','OTKAZANA')),
    CONSTRAINT ex_izlozba_sala_period EXCLUDE USING gist (sala_id WITH =, tstzrange(datum_pocetka, datum_zavrsetka, '[)') WITH &&) WHERE (status <> 'OTKAZANA')
);

CREATE INDEX ix_izlozba_sala_id ON izlozba (sala_id);

CREATE INDEX ix_izlozba_naziv ON izlozba (naziv);

CREATE TABLE termin_izlozbe (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    izlozba_id bigint NOT NULL REFERENCES izlozba(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    pocetak timestamp with time zone NOT NULL,
    kraj timestamp with time zone NOT NULL,
    kapacitet integer NOT NULL,
    status varchar(32) NOT NULL,
    CONSTRAINT ck_termin_period CHECK (kraj > pocetak),
    CONSTRAINT ck_termin_kapacitet CHECK (kapacitet >= 0),
    CONSTRAINT ck_termin_status CHECK (status IN ('OTVOREN','POPUNJEN','ZAVRSEN','OTKAZAN'))
);

CREATE INDEX ix_termin_izlozbe_izlozba_id ON termin_izlozbe (izlozba_id);

CREATE TABLE autor (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ime text NOT NULL,
    prezime text,
    godina_rodjenja integer,
    godina_smrti integer,
    biografija text
);

CREATE TABLE eksponat (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv text NOT NULL,
    godina_nastanka text,
    tip text,
    materijal text,
    poreklo text,
    opis text,
    inventarski_broj text NOT NULL UNIQUE
);

CREATE TABLE ucesce_eksponata_na_izlozbi (
    id_ucesca bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    izlozba_id bigint NOT NULL REFERENCES izlozba(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    eksponat_id bigint NOT NULL REFERENCES eksponat(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    datum_postavljanja timestamp with time zone,
    datum_uklanjanja timestamp with time zone,
    pozicija text,
    redosled_obilaska integer,
    kontekstualni_opis text,
    qr_token text NOT NULL UNIQUE,
    qr_putanja text
);

CREATE INDEX ix_ucesce_eksponata_na_izlozbi_izlozba_id ON ucesce_eksponata_na_izlozbi (izlozba_id);

CREATE INDEX ix_ucesce_eksponata_na_izlozbi_eksponat_id ON ucesce_eksponata_na_izlozbi (eksponat_id);

CREATE TABLE digitalni_sadrzaj (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ucesce_id bigint NOT NULL REFERENCES ucesce_eksponata_na_izlozbi(id_ucesca) ON DELETE RESTRICT ON UPDATE RESTRICT,
    tip_sadrzaja varchar(32) NOT NULL,
    putanja text NOT NULL,
    jezik text,
    verzija integer NOT NULL,
    generisan_automatski boolean NOT NULL,
    datum_kreiranja timestamp with time zone NOT NULL,
    CONSTRAINT ck_sadrzaj_tip CHECK (tip_sadrzaja IN ('SLIKA','TEKST','AUDIO'))
);

CREATE INDEX ix_digitalni_sadrzaj_ucesce_id ON digitalni_sadrzaj (ucesce_id);

CREATE TABLE autorstvo (
    autor_id bigint NOT NULL REFERENCES autor(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    eksponat_id bigint NOT NULL REFERENCES eksponat(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    vrsta_doprinosa text,
    napomena text,
    PRIMARY KEY (autor_id, eksponat_id)
);
CREATE INDEX ix_autorstvo_eksponat ON autorstvo (eksponat_id);
CREATE TABLE cenovnik_izlozbe (
    izlozba_id bigint NOT NULL REFERENCES izlozba(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    datum_vazenja_od timestamp with time zone NOT NULL,
    kategorija text NOT NULL,
    datum_vazenja_do timestamp with time zone,
    cena numeric(19,2) NOT NULL,
    napomena text,
    PRIMARY KEY (izlozba_id, datum_vazenja_od, kategorija)
);
CREATE INDEX ix_termin_pocetak ON termin_izlozbe (pocetak);

-- Check all surviving affected exhibitions at commit, permitting atomic creation
-- and deletion of an exhibition together with its terms.
CREATE FUNCTION proveri_termine_izlozbe() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    ids bigint[];
    target_id bigint;
    e izlozba%ROWTYPE;
BEGIN
    IF TG_TABLE_NAME = 'izlozba' THEN
        ids := ARRAY[NEW.id];
    ELSIF TG_OP = 'INSERT' THEN
        ids := ARRAY[NEW.izlozba_id];
    ELSIF TG_OP = 'DELETE' THEN
        ids := ARRAY[OLD.izlozba_id];
    ELSE
        ids := ARRAY[OLD.izlozba_id, NEW.izlozba_id];
    END IF;
    FOR target_id IN SELECT DISTINCT unnest(ids) ORDER BY 1 LOOP
        SELECT * INTO e FROM izlozba WHERE id = target_id FOR UPDATE;
        IF FOUND THEN
            IF NOT EXISTS (SELECT 1 FROM termin_izlozbe WHERE izlozba_id = target_id) THEN
                RAISE EXCEPTION 'Exhibition must have at least one term' USING ERRCODE = '23514';
            END IF;
            IF EXISTS (SELECT 1 FROM termin_izlozbe t WHERE t.izlozba_id = target_id
                       AND (t.pocetak < e.datum_pocetka OR t.kraj > e.datum_zavrsetka)) THEN
                RAISE EXCEPTION 'Term must be within exhibition period' USING ERRCODE = '23514';
            END IF;
        END IF;
    END LOOP;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER ct_izlozba_termini
AFTER INSERT OR UPDATE ON izlozba DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION proveri_termine_izlozbe();
CREATE CONSTRAINT TRIGGER ct_termin_izlozba
AFTER INSERT OR UPDATE OR DELETE ON termin_izlozbe DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION proveri_termine_izlozbe();
