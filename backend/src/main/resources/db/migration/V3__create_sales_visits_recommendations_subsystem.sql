-- Subsystem 3; approved relationships only. V1 and V2 remain immutable.
CREATE TABLE ulaznica (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 posetilac_id bigint REFERENCES posetilac(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 termin_id bigint NOT NULL REFERENCES termin_izlozbe(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 cenovnik_izlozba_id bigint NOT NULL,
 cenovnik_vazi_od timestamptz NOT NULL,
 kategorija_cene text NOT NULL,
 datum_kupovine timestamptz NOT NULL,
 cena_placena numeric(19,2) NOT NULL,
 status varchar(32) NOT NULL CHECK (status IN ('KUPLJENA','AKTIVNA','ISKORISCENA','ISTEKLA','OTKAZANA')),
 qr_token text NOT NULL UNIQUE,
 vazi_do timestamptz NOT NULL CHECK (vazi_do > datum_kupovine),
 FOREIGN KEY (cenovnik_izlozba_id,cenovnik_vazi_od,kategorija_cene)
 REFERENCES cenovnik_izlozbe(izlozba_id,datum_vazenja_od,kategorija)
 ON DELETE RESTRICT ON UPDATE RESTRICT
);
CREATE INDEX ix_ulaznica_posetilac ON ulaznica(posetilac_id);
CREATE INDEX ix_ulaznica_termin ON ulaznica(termin_id);
CREATE INDEX ix_ulaznica_cenovnik ON ulaznica(cenovnik_izlozba_id,cenovnik_vazi_od,kategorija_cene);
CREATE INDEX ix_ulaznica_rok ON ulaznica(vazi_do);
CREATE TABLE transakcija (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ulaznica_id bigint NOT NULL REFERENCES ulaznica(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 iznos numeric(19,2) NOT NULL,
 nacin_placanja varchar(32) NOT NULL CHECK (nacin_placanja IN ('KARTICA','GOTOVINA','DRUGO')),
 status varchar(32) NOT NULL CHECK (status IN ('POKRENUTA','USPESNA','NEUSPESNA','REFUNDIRANA')),
 eksterna_referenca text,
 datum_transakcije timestamptz NOT NULL
);
CREATE INDEX ix_transakcija_ulaznica ON transakcija(ulaznica_id);
CREATE TABLE poseta (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ulaznica_id bigint NOT NULL UNIQUE REFERENCES ulaznica(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 vreme_ulaska timestamptz NOT NULL,
 vreme_izlaska timestamptz,
 status varchar(32) NOT NULL CHECK (status IN ('AKTIVNA','ZAVRSENA')),
 CHECK (vreme_izlaska IS NULL OR vreme_izlaska >= vreme_ulaska),
 CHECK ((status='AKTIVNA' AND vreme_izlaska IS NULL) OR (status='ZAVRSENA' AND vreme_izlaska IS NOT NULL))
);
CREATE TABLE skeniranje_eksponata (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 poseta_id bigint NOT NULL REFERENCES poseta(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 ucesce_id bigint NOT NULL REFERENCES ucesce_eksponata_na_izlozbi(id_ucesca) ON DELETE RESTRICT ON UPDATE RESTRICT,
 vreme_skeniranja timestamptz NOT NULL,
 trajanje_pregleda integer CHECK (trajanje_pregleda >= 0)
);
CREATE INDEX ix_skeniranje_poseta_vreme ON skeniranje_eksponata(poseta_id,vreme_skeniranja,id);
CREATE INDEX ix_skeniranje_ucesce ON skeniranje_eksponata(ucesce_id);
CREATE TABLE ocena_izlozbe (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 poseta_id bigint NOT NULL UNIQUE REFERENCES poseta(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 ocena integer NOT NULL CHECK (ocena BETWEEN 1 AND 5),
 komentar text,
 datum_ocene timestamptz NOT NULL
);
CREATE TABLE preporucena_ruta (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 poseta_id bigint NOT NULL REFERENCES poseta(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 datum_generisanja timestamptz NOT NULL,
 kriterijum varchar(32) NOT NULL CHECK (kriterijum IN ('INTERESOVANJA','BLIZINA','POPULARNOST','KOMBINACIJA')),
 status varchar(32) NOT NULL CHECK (status IN ('AKTIVNA','ZAVRSENA'))
);
CREATE INDEX ix_ruta_poseta ON preporucena_ruta(poseta_id);
CREATE TABLE stavka_rute (
 ruta_id bigint NOT NULL REFERENCES preporucena_ruta(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 redni_broj integer NOT NULL CHECK (redni_broj >= 1),
 ucesce_id bigint NOT NULL REFERENCES ucesce_eksponata_na_izlozbi(id_ucesca) ON DELETE RESTRICT ON UPDATE RESTRICT,
 obrazlozenje text NOT NULL,
 posecena boolean NOT NULL,
 PRIMARY KEY (ruta_id,redni_broj),
 UNIQUE (ruta_id,ucesce_id)
);
CREATE INDEX ix_stavka_ucesce ON stavka_rute(ucesce_id);

CREATE FUNCTION proveri_kapacitet_ulaznica() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE ids bigint[]; target bigint; t termin_izlozbe%ROWTYPE;
BEGIN
 IF TG_TABLE_NAME='termin_izlozbe' THEN ids:=ARRAY[NEW.id];
 ELSIF TG_OP='INSERT' THEN ids:=ARRAY[NEW.termin_id];
 ELSE ids:=ARRAY[OLD.termin_id,NEW.termin_id]; END IF;
 FOR target IN SELECT DISTINCT unnest(ids) ORDER BY 1 LOOP
  SELECT * INTO t FROM termin_izlozbe WHERE id=target FOR UPDATE;
  IF FOUND THEN
   IF (SELECT count(*) FROM ulaznica WHERE termin_id=target AND status<>'OTKAZANA') > t.kapacitet THEN
    RAISE EXCEPTION 'Ticket capacity exceeded' USING ERRCODE='23514';
   END IF;
   IF EXISTS (SELECT 1 FROM ulaznica WHERE termin_id=target AND cenovnik_izlozba_id<>t.izlozba_id) THEN
    RAISE EXCEPTION 'Ticket price and term must belong to the same exhibition' USING ERRCODE='23514';
   END IF;
  END IF;
 END LOOP;
 RETURN NULL;
END; $$;
CREATE CONSTRAINT TRIGGER ct_ulaznica_kapacitet AFTER INSERT OR UPDATE ON ulaznica
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION proveri_kapacitet_ulaznica();
CREATE CONSTRAINT TRIGGER ct_termin_ulaznice AFTER UPDATE ON termin_izlozbe
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION proveri_kapacitet_ulaznica();

CREATE FUNCTION proveri_ulaznicu() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE price cenovnik_izlozbe%ROWTYPE;
BEGIN
 IF TG_OP='UPDATE' AND OLD.status<>'OTKAZANA' AND
    (NEW.termin_id,NEW.posetilac_id,NEW.cenovnik_izlozba_id,NEW.cenovnik_vazi_od,NEW.kategorija_cene,NEW.cena_placena,NEW.datum_kupovine,NEW.qr_token,NEW.vazi_do)
    IS DISTINCT FROM
    (OLD.termin_id,OLD.posetilac_id,OLD.cenovnik_izlozba_id,OLD.cenovnik_vazi_od,OLD.kategorija_cene,OLD.cena_placena,OLD.datum_kupovine,OLD.qr_token,OLD.vazi_do) THEN
  RAISE EXCEPTION 'Purchased ticket snapshot is immutable' USING ERRCODE='23514';
 END IF;
 IF TG_OP='INSERT' OR (OLD.status='OTKAZANA' AND NEW.status='KUPLJENA') THEN
  SELECT * INTO price FROM cenovnik_izlozbe WHERE izlozba_id=NEW.cenovnik_izlozba_id AND datum_vazenja_od=NEW.cenovnik_vazi_od AND kategorija=NEW.kategorija_cene FOR SHARE;
  IF NOT FOUND OR NEW.datum_kupovine<price.datum_vazenja_od OR
     (price.datum_vazenja_do IS NOT NULL AND NEW.datum_kupovine>=price.datum_vazenja_do) OR NEW.cena_placena<>price.cena THEN
   RAISE EXCEPTION 'Invalid price snapshot' USING ERRCODE='23514';
  END IF;
 END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER tr_ulaznica_snapshot BEFORE INSERT OR UPDATE ON ulaznica FOR EACH ROW EXECUTE FUNCTION proveri_ulaznicu();

CREATE FUNCTION proveri_ulaznica_transakcije() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE ids bigint[]; target bigint;
BEGIN
 IF TG_TABLE_NAME='ulaznica' THEN ids:=ARRAY[NEW.id];
 ELSIF TG_OP='INSERT' THEN ids:=ARRAY[NEW.ulaznica_id];
 ELSIF TG_OP='DELETE' THEN ids:=ARRAY[OLD.ulaznica_id];
 ELSE ids:=ARRAY[OLD.ulaznica_id,NEW.ulaznica_id]; END IF;
 FOR target IN SELECT DISTINCT unnest(ids) ORDER BY 1 LOOP
  PERFORM 1 FROM ulaznica WHERE id=target FOR UPDATE;
  IF FOUND AND NOT EXISTS (SELECT 1 FROM transakcija WHERE ulaznica_id=target) THEN
   RAISE EXCEPTION 'Ticket requires at least one transaction' USING ERRCODE='23514';
  END IF;
  IF EXISTS (SELECT 1 FROM ulaznica u WHERE u.id=target AND u.status<>'OTKAZANA'
    AND NOT EXISTS (SELECT 1 FROM transakcija t WHERE t.ulaznica_id=u.id AND t.status='USPESNA')) THEN
   RAISE EXCEPTION 'Non-cancelled ticket requires successful payment' USING ERRCODE='23514';
  END IF;
 END LOOP;
 RETURN NULL;
END; $$;
CREATE CONSTRAINT TRIGGER ct_ulaznica_transakcije AFTER INSERT OR UPDATE ON ulaznica
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION proveri_ulaznica_transakcije();
CREATE CONSTRAINT TRIGGER ct_transakcija_ulaznica AFTER INSERT OR UPDATE OR DELETE ON transakcija
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION proveri_ulaznica_transakcije();

CREATE FUNCTION proveri_posetu() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE u ulaznica%ROWTYPE; t termin_izlozbe%ROWTYPE;
BEGIN
 SELECT * INTO u FROM ulaznica WHERE id=NEW.ulaznica_id FOR UPDATE;
 SELECT * INTO t FROM termin_izlozbe WHERE id=u.termin_id;
 IF u.status<>'KUPLJENA' OR NEW.vreme_ulaska<t.pocetak OR NEW.vreme_ulaska>=t.kraj
    OR NEW.vreme_ulaska>=u.vazi_do OR t.status IN ('OTKAZAN','ZAVRSEN')
    OR NOT EXISTS (SELECT 1 FROM transakcija WHERE ulaznica_id=u.id AND status='USPESNA') THEN
  RAISE EXCEPTION 'Ticket cannot open this visit' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER tr_poseta_validacija BEFORE INSERT ON poseta FOR EACH ROW EXECUTE FUNCTION proveri_posetu();

CREATE FUNCTION proveri_skeniranje() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS (
  SELECT 1 FROM poseta p JOIN ulaznica u ON u.id=p.ulaznica_id
  JOIN termin_izlozbe t ON t.id=u.termin_id
  JOIN ucesce_eksponata_na_izlozbi e ON e.id_ucesca=NEW.ucesce_id AND e.izlozba_id=t.izlozba_id
  WHERE p.id=NEW.poseta_id AND p.status='AKTIVNA' AND NEW.vreme_skeniranja>=p.vreme_ulaska
   AND NEW.vreme_skeniranja<t.kraj AND NEW.vreme_skeniranja<u.vazi_do
   AND (e.datum_postavljanja IS NULL OR e.datum_postavljanja<=NEW.vreme_skeniranja)
   AND (e.datum_uklanjanja IS NULL OR e.datum_uklanjanja>NEW.vreme_skeniranja)
 ) THEN RAISE EXCEPTION 'Scan requires an active visit and available participation in the same exhibition' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER tr_skeniranje_validacija BEFORE INSERT ON skeniranje_eksponata FOR EACH ROW EXECUTE FUNCTION proveri_skeniranje();

CREATE FUNCTION proveri_ocenu() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 PERFORM 1 FROM poseta WHERE id=NEW.poseta_id AND status='ZAVRSENA' FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Rating requires a finished visit' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER tr_ocena_validacija BEFORE INSERT OR UPDATE ON ocena_izlozbe FOR EACH ROW EXECUTE FUNCTION proveri_ocenu();

CREATE FUNCTION proveri_stavke_rute() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE ids bigint[]; target bigint;
BEGIN
 IF TG_TABLE_NAME='preporucena_ruta' THEN ids:=ARRAY[NEW.id];
 ELSIF TG_OP='INSERT' THEN ids:=ARRAY[NEW.ruta_id];
 ELSIF TG_OP='DELETE' THEN ids:=ARRAY[OLD.ruta_id];
 ELSE ids:=ARRAY[OLD.ruta_id,NEW.ruta_id]; END IF;
 FOR target IN SELECT DISTINCT unnest(ids) ORDER BY 1 LOOP
  PERFORM 1 FROM preporucena_ruta WHERE id=target FOR UPDATE;
  IF FOUND AND NOT EXISTS (SELECT 1 FROM stavka_rute WHERE ruta_id=target) THEN
   RAISE EXCEPTION 'Route requires at least one item' USING ERRCODE='23514';
  END IF;
  IF EXISTS (SELECT 1 FROM stavka_rute s JOIN preporucena_ruta r ON r.id=s.ruta_id
    JOIN poseta p ON p.id=r.poseta_id JOIN ulaznica u ON u.id=p.ulaznica_id JOIN termin_izlozbe t ON t.id=u.termin_id
    JOIN ucesce_eksponata_na_izlozbi e ON e.id_ucesca=s.ucesce_id
    WHERE r.id=target AND e.izlozba_id<>t.izlozba_id) THEN
   RAISE EXCEPTION 'Route item belongs to a different exhibition' USING ERRCODE='23514';
  END IF;
 END LOOP;
 RETURN NULL;
END; $$;
CREATE CONSTRAINT TRIGGER ct_ruta_stavke AFTER INSERT OR UPDATE ON preporucena_ruta
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION proveri_stavke_rute();
CREATE CONSTRAINT TRIGGER ct_stavka_ruta AFTER INSERT OR UPDATE OR DELETE ON stavka_rute
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION proveri_stavke_rute();

