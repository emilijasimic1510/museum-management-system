CREATE FUNCTION proveri_nalog_uloge() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE ids bigint[]; target bigint;
BEGIN
    IF TG_TABLE_NAME = 'korisnicki_nalog' THEN ids := ARRAY[NEW.id];
    ELSIF TG_OP = 'INSERT' THEN ids := ARRAY[NEW.nalog_id];
    ELSIF TG_OP = 'DELETE' THEN ids := ARRAY[OLD.nalog_id];
    ELSE ids := ARRAY[OLD.nalog_id, NEW.nalog_id]; END IF;
    FOR target IN SELECT DISTINCT unnest(ids) ORDER BY 1 LOOP
        PERFORM 1 FROM korisnicki_nalog WHERE id=target FOR UPDATE;
        IF FOUND AND NOT EXISTS (SELECT 1 FROM nalog_uloga WHERE nalog_id=target) THEN
            RAISE EXCEPTION 'Account requires at least one role' USING ERRCODE='23514';
        END IF;
    END LOOP;
    RETURN NULL;
END; $$;
CREATE CONSTRAINT TRIGGER ct_nalog_uloge AFTER INSERT OR UPDATE ON korisnicki_nalog
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION proveri_nalog_uloge();
CREATE CONSTRAINT TRIGGER ct_uloge_nalog AFTER INSERT OR UPDATE OR DELETE ON nalog_uloga
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION proveri_nalog_uloge();

CREATE FUNCTION proveri_zaposleni_podtip() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE ids bigint[]; target bigint; expected text; actual text; total integer;
BEGIN
    IF TG_TABLE_NAME='zaposleni' THEN
        IF TG_OP='DELETE' THEN ids:=ARRAY[OLD.id]; ELSE ids:=ARRAY[NEW.id]; END IF;
    ELSIF TG_OP='INSERT' THEN ids:=ARRAY[NEW.zaposleni_id];
    ELSIF TG_OP='DELETE' THEN ids:=ARRAY[OLD.zaposleni_id];
    ELSE ids:=ARRAY[OLD.zaposleni_id,NEW.zaposleni_id]; END IF;
    FOR target IN SELECT DISTINCT unnest(ids) ORDER BY 1 LOOP
        SELECT tip_zaposlenog INTO expected FROM zaposleni WHERE id=target FOR UPDATE;
        IF FOUND THEN
            SELECT count(*), min(tip) INTO total,actual FROM (
                SELECT 'CURATOR' AS tip FROM kustos WHERE zaposleni_id=target
                UNION ALL SELECT 'GUIDE' FROM vodic WHERE zaposleni_id=target
                UNION ALL SELECT 'CASHIER' FROM blagajnik WHERE zaposleni_id=target
                UNION ALL SELECT 'MANAGER' FROM menadzer WHERE zaposleni_id=target
                UNION ALL SELECT 'ADMINISTRATOR' FROM administrator WHERE zaposleni_id=target
            ) subtype;
            IF total<>1 OR actual<>expected THEN
                RAISE EXCEPTION 'Employee requires exactly one matching subtype' USING ERRCODE='23514';
            END IF;
        END IF;
    END LOOP;
    RETURN NULL;
END; $$;

CREATE CONSTRAINT TRIGGER ct_zaposleni_isa AFTER INSERT OR UPDATE OR DELETE ON zaposleni
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION proveri_zaposleni_podtip();

