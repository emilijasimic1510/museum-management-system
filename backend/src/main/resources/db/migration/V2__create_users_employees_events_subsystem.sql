CREATE TABLE korisnicki_nalog (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE,
    lozinka_hash text NOT NULL,
    aktivan boolean NOT NULL,
    datum_registracije timestamp with time zone NOT NULL,
    poslednja_prijava timestamp with time zone,
    CONSTRAINT ck_password_hash CHECK (lozinka_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$')
);

CREATE TABLE uloga (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv varchar(32) NOT NULL UNIQUE,
    opis text,
    CONSTRAINT ck_uloga CHECK (naziv IN ('VISITOR','CURATOR','CASHIER','GUIDE','MANAGER','ADMINISTRATOR'))
);

CREATE TABLE posetilac (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nalog_id bigint NOT NULL REFERENCES korisnicki_nalog(id) ON DELETE RESTRICT ON UPDATE RESTRICT UNIQUE,
    ime text NOT NULL,
    prezime text NOT NULL,
    telefon text,
    saglasnost_za_preporuke boolean NOT NULL
);

CREATE TABLE zaposleni (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nalog_id bigint NOT NULL REFERENCES korisnicki_nalog(id) ON DELETE RESTRICT ON UPDATE RESTRICT UNIQUE,
    muzej_id bigint NOT NULL REFERENCES muzej(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    ime text NOT NULL,
    prezime text NOT NULL,
    telefon text,
    datum_zaposlenja date NOT NULL,
    nadredjeni_id bigint REFERENCES zaposleni(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    tip_zaposlenog varchar(32) NOT NULL CHECK (tip_zaposlenog IN ('CURATOR','GUIDE','CASHIER','MANAGER','ADMINISTRATOR')),
    CONSTRAINT ck_nadredjeni CHECK (nadredjeni_id <> id)
);

CREATE INDEX ix_zaposleni_muzej_id ON zaposleni (muzej_id);

CREATE INDEX ix_zaposleni_nadredjeni_id ON zaposleni (nadredjeni_id);

CREATE TABLE interesovanje (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv text NOT NULL UNIQUE,
    opis text
);

CREATE TABLE kustos (
    zaposleni_id bigint PRIMARY KEY REFERENCES zaposleni(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    specijalizacija text
);

CREATE TABLE vodic (
    zaposleni_id bigint PRIMARY KEY REFERENCES zaposleni(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    primarni_jezik text
);

CREATE TABLE blagajnik (
    zaposleni_id bigint PRIMARY KEY REFERENCES zaposleni(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    oznaka_saltera text
);

CREATE TABLE menadzer (
    zaposleni_id bigint PRIMARY KEY REFERENCES zaposleni(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    nivo_izvestavanja text
);

CREATE TABLE administrator (
    zaposleni_id bigint PRIMARY KEY REFERENCES zaposleni(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    nivo_administracije text
);

CREATE TABLE dogadjaj (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    izlozba_id bigint NOT NULL REFERENCES izlozba(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    vodic_id bigint REFERENCES vodic(zaposleni_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    naziv text NOT NULL,
    tip varchar(32) NOT NULL,
    pocetak timestamp with time zone NOT NULL,
    kraj timestamp with time zone NOT NULL,
    kapacitet integer NOT NULL,
    jezik text,
    status varchar(32) NOT NULL,
    CONSTRAINT ck_dogadjaj_tip CHECK (tip IN ('TURA','PREDAVANJE','RADIONICA')),
    CONSTRAINT ck_dogadjaj_status CHECK (status IN ('PLANIRAN','POPUNJEN','ZAVRSEN','OTKAZAN')),
    CONSTRAINT ck_dogadjaj_interval CHECK (kraj > pocetak),
    CONSTRAINT ck_dogadjaj_kapacitet CHECK (kapacitet >= 0)
);

CREATE INDEX ix_dogadjaj_izlozba_id ON dogadjaj (izlozba_id);

CREATE INDEX ix_dogadjaj_vodic_id ON dogadjaj (vodic_id);

CREATE TABLE nalog_uloga (
    nalog_id bigint NOT NULL REFERENCES korisnicki_nalog(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    uloga_id bigint NOT NULL REFERENCES uloga(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    datum_dodele timestamp with time zone NOT NULL,
    dodelio_id bigint REFERENCES korisnicki_nalog(id) ON DELETE SET NULL ON UPDATE RESTRICT,
    PRIMARY KEY (nalog_id, uloga_id)
);

CREATE INDEX ix_nalog_uloga_uloga_id ON nalog_uloga (uloga_id);

CREATE TABLE posetilac_interesovanje (
    posetilac_id bigint NOT NULL REFERENCES posetilac(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    interesovanje_id bigint NOT NULL REFERENCES interesovanje(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    nivo integer,
    PRIMARY KEY (posetilac_id, interesovanje_id)
);

CREATE INDEX ix_posetilac_interesovanje_interesovanje_id ON posetilac_interesovanje (interesovanje_id);

CREATE TABLE prijava_na_dogadjaj (
    posetilac_id bigint NOT NULL REFERENCES posetilac(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    dogadjaj_id bigint NOT NULL REFERENCES dogadjaj(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    datum_prijave timestamp with time zone NOT NULL,
    status varchar(32) NOT NULL,
    PRIMARY KEY (posetilac_id, dogadjaj_id),
    CONSTRAINT ck_prijava_status CHECK (status IN ('PRIJAVLJEN','PRISUSTVOVAO','OTKAZAN'))
);

CREATE INDEX ix_prijava_na_dogadjaj_dogadjaj_id ON prijava_na_dogadjaj (dogadjaj_id);

