CREATE FUNCTION proveri_kapacitet_dogadjaja() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE ids bigint[]; target bigint; available integer;
BEGIN
    IF TG_TABLE_NAME='dogadjaj' THEN ids:=ARRAY[NEW.id];
    ELSIF TG_OP='INSERT' THEN ids:=ARRAY[NEW.dogadjaj_id];
    ELSIF TG_OP='DELETE' THEN ids:=ARRAY[OLD.dogadjaj_id];
    ELSE ids:=ARRAY[OLD.dogadjaj_id,NEW.dogadjaj_id]; END IF;
    FOR target IN SELECT DISTINCT unnest(ids) ORDER BY 1 LOOP
        SELECT kapacitet INTO available FROM dogadjaj WHERE id=target FOR UPDATE;
        IF FOUND AND (SELECT count(*) FROM prijava_na_dogadjaj WHERE dogadjaj_id=target AND status<>'OTKAZAN') > available THEN
            RAISE EXCEPTION 'Event capacity exceeded' USING ERRCODE='23514';
        END IF;
    END LOOP;
    RETURN NULL;
END; $$;
CREATE CONSTRAINT TRIGGER ct_dogadjaj_kapacitet AFTER INSERT OR UPDATE ON dogadjaj
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION proveri_kapacitet_dogadjaja();
CREATE CONSTRAINT TRIGGER ct_prijava_kapacitet AFTER INSERT OR UPDATE OR DELETE ON prijava_na_dogadjaj
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION proveri_kapacitet_dogadjaja();
