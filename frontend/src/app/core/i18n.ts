const selectedLanguage=signal<Language>('sr');
const sourceKeys=new Map<string,string>();
for(const [key,value] of Object.entries(SR))sourceKeys.set(value,key);
for(const [key,value] of Object.entries(EN))sourceKeys.set(value,key);
export function translate(key:string):string {
  const resolved=SR[key]!==undefined?key:sourceKeys.get(key);
  if(resolved)return (selectedLanguage()==='en'?EN[resolved]||SR[resolved]:SR[resolved]);
  // Unknown keys must never leak into the interface. Plain data remains unchanged.
  return /^[a-zA-Z]+\.[a-zA-Z]/.test(key)?'—':key;
}
export function uiLocale(){return selectedLanguage()==='sr'?'sr-Latn-RS':'en-US';}
export function translationKeys():string[]{return Object.keys(SR);}
export function translationIntegrity(){const sr=new Set(Object.keys(SR)),en=new Set(Object.keys(EN));return {sr:[...sr],en:[...en],missingInEnglish:[...sr].filter(k=>!en.has(k)),missingInSerbian:[...en].filter(k=>!sr.has(k))};}
export function enumLabel(value:string|null|undefined,kind='status'):string {
  if(!value)return '—';
  const code=kind==='role'?value.replace(/^ROLE_/,''):value;
  const key=kind+'.'+code;
  return SR[key]!==undefined?translate(key):value;
}
@Injectable({providedIn:'root'})
export class I18n {
  readonly language=selectedLanguage;
  constructor(){this.language.set(this.restore());}
  private restore():Language {try{return localStorage.getItem(STORAGE_KEY)==='en'?'en':'sr';}catch{return 'sr';}}
  setLanguage(language:Language){this.language.set(language);try{localStorage.setItem(STORAGE_KEY,language);}catch{}}
  toggle(){this.setLanguage(this.language()==='sr'?'en':'sr');}
  t(key:string):string {return translate(key);}
  status(value:string){return enumLabel(value);}
  role(value:string){return enumLabel(value,'role');}
  payment(value:string){return enumLabel(value,'payment');}
  date(value:string|Date,options?:Intl.DateTimeFormatOptions){return new Intl.DateTimeFormat(this.language()==='sr'?'sr-Latn-RS':'en-US',options).format(new Date(value));}
  number(value:number,options?:Intl.NumberFormatOptions){return new Intl.NumberFormat(this.language()==='sr'?'sr-Latn-RS':'en-US',options).format(value);}
}
